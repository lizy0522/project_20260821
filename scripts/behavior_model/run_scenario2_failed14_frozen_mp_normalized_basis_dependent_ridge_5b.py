"""Structured basis-dependent Ridge scan for the fixed Frozen MP model.

The ten Frozen MP columns are first normalized with a train-only RMS scale.
Rather than fitting ten free regularization values, the diagonal penalty is
generated by three shared hyperparameters:

    lambda_(p,m) = lambda0 * alpha**g(p) * beta**m

Only A/C contiguous blocked-CV is used to select the three hyperparameters.
B targets are materialized only after the selected triple is frozen.  The
task writes exactly three result files and keeps all other diagnostics in
memory.
"""

