def main() -> None:
    freeze_support()
    print(f"Starting {TASK_NAME}", flush=True)
    if len(FAILED_STATE_IDS) != 14 or K != 10 or DMAX != 2 or len(LOG10_LAMBDA0_COARSE) != 13 or len(ALPHA_COARSE) != 6 or len(BETA_COARSE) != 4:
        raise RuntimeError("fixed experiment definition gate failed")
    before = _uniform_snapshot()
    reference = _uniform_load_reference()
    logical_cpu_count = int(os.cpu_count() or 1)
    workers = max(1, int(math.floor(CPU_TARGET * logical_cpu_count)))
    print(f"logical_cpu_count={logical_cpu_count}; worker_count={workers}; target={CPU_TARGET:.2f}", flush=True)
    frozen_gate = _uniform_frozen_reproduction_gate(reference)
    if not frozen_gate["pass"]:
        raise RuntimeError(f"Frozen reproduction gate failed: {frozen_gate['maximum_abs_error_dB']}")
    lambda_gate = _lambda_vector_gate()
    if not lambda_gate["pass"]:
        raise RuntimeError("basis-dependent lambda-vector gate failed")
    print(f"Frozen reproduction gate PASS; max_abs_error_dB={frozen_gate['maximum_abs_error_dB']:.3g}", flush=True)
    print("basis-dependent lambda-vector gate PASS", flush=True)

    discovery_payload, discovery_records = _prepare_discovery_payload()
    coarse_configs = [(10.0 ** float(log_lambda), float(alpha), float(beta_memory)) for log_lambda in LOG10_LAMBDA0_COARSE for alpha in ALPHA_COARSE for beta_memory in BETA_COARSE]
    coarse_frame = _configuration_rows("coarse", coarse_configs, 0)
    coarse_summary = _scan_configurations(coarse_frame, discovery_payload, workers)
    coarse_best, coarse_selection = _select_configuration(coarse_summary)
    print(f"coarse best: lambda0={coarse_best.lambda0:.17g}, alpha={coarse_best.alpha:.17g}, beta={coarse_best.beta_memory:.17g}, BalancedMedian={coarse_best.BalancedMedian_dB:.6f} dB", flush=True)
    refine_configs_all = _local_refinement_configs(coarse_best)
    coarse_keys = {
        (round(float(np.log10(lambda0)), 12), round(float(np.log2(alpha)), 12), round(float(np.log2(beta_memory)), 12))
        for lambda0, alpha, beta_memory in coarse_configs
    }
    refine_configs = [
        config
        for config in refine_configs_all
        if (round(float(np.log10(config[0])), 12), round(float(np.log2(config[1])), 12), round(float(np.log2(config[2])), 12)) not in coarse_keys
    ]
    refine_frame = _configuration_rows("refinement", refine_configs, len(coarse_configs))
    refine_summary = _scan_configurations(refine_frame, discovery_payload, workers)
    combined_summary = pd.concat([coarse_summary, refine_summary], ignore_index=True)
    selected_row, selection = _select_configuration(combined_summary)
    selection["coarse_best"] = {key: float(coarse_best[key]) if key in {"lambda0", "alpha", "beta_memory", "BalancedMedian_dB"} else coarse_best[key] for key in ("lambda0", "alpha", "beta_memory", "BalancedMedian_dB")}
    print(f"selected weighted Ridge: lambda0={selection['selected_lambda0']:.17g}, alpha={selection['selected_alpha']:.17g}, beta={selection['selected_beta_memory']:.17g}, BalancedMedian={selection['best_balanced_median_dB']:.6f} dB", flush=True)
    del discovery_payload

    final_rows, conditions = _fit_final_rows(selection["selected_lambda0"], selection["selected_alpha"], selection["selected_beta_memory"])
    uniform_gate = _uniform_equivalence_gate(final_rows)
    if not uniform_gate["pass"]:
        raise RuntimeError(f"uniform-equivalence gate failed: {uniform_gate['maximum_abs_difference_dB']}")
    RESULT_ROOT.mkdir(parents=True, exist_ok=True)
    combined_summary["is_selected"] = combined_summary["config_id"].eq(int(selection["selected_config_id"]))
    _write_frame(combined_summary.drop(columns=["rank_min"]), RESULT_ROOT / "ridge_search_summary.csv")
    _write_frame(final_rows.drop(columns=[column for column in final_rows.columns if column.endswith("_gap")]), RESULT_ROOT / "final_per_state_metrics.csv")
    after = _uniform_snapshot()
    protection = _uniform_protection_check(before, after)
    if not protection["all_protected_unchanged"]:
        raise RuntimeError("raw data or protected historical result changed")
    summary = _summary_text(combined_summary, selection, final_rows, conditions, uniform_gate, lambda_gate, frozen_gate, protection, workers, len(coarse_configs), len(refine_configs))
    (RESULT_ROOT / "final_result_summary.txt").write_text(summary, encoding="utf-8")
    timestamp = datetime.now(UTC).isoformat()
    log = (
        f"{TASK_NAME} completed: states=14, coarse_configs={len(coarse_configs)}, refinement_configs={len(refine_configs)}, "
        f"total_configs={len(combined_summary)}, selected_lambda0={selection['selected_lambda0']:.17g}, alpha={selection['selected_alpha']:.17g}, beta={selection['selected_beta_memory']:.17g}, "
        f"CV_fits={(len(coarse_configs) + len(refine_configs)) * 14 * 2 * 3}, workers={workers}, frozen_gate={frozen_gate['pass']}, lambda_vector_gate={lambda_gate['pass']}, uniform_gate={uniform_gate['pass']}, raw/protected unchanged={protection['all_protected_unchanged']}. "
        f"Only three result files were written under {RESULT_ROOT}; no figures, Excel, cache, coefficients, or retrieval were generated."
    )
    WORK_LOG.parent.mkdir(parents=True, exist_ok=True)
    HANDOFF_LOG.parent.mkdir(parents=True, exist_ok=True)
    with WORK_LOG.open("a", encoding="utf-8") as handle:
        handle.write(f"\n\n[{timestamp}] {TASK_NAME}\n{log}\n")
    with HANDOFF_LOG.open("a", encoding="utf-8") as handle:
        handle.write(f"\n\n{timestamp} | behavior_model 新派生任务：Frozen MP normalized basis-dependent Ridge\n{log}\n")
    print(log, flush=True)


if __name__ == "__main__":
    main()
