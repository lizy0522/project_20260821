def _lambda_vector(lambda0: float, alpha: float, beta_memory: float) -> np.ndarray:
    lambda0 = float(lambda0)
    alpha = float(alpha)
    beta_memory = float(beta_memory)
    if not np.isfinite(lambda0) or lambda0 <= 0 or not np.isfinite(alpha) or alpha < 1 or not np.isfinite(beta_memory) or beta_memory < 1:
        raise ValueError("lambda0 must be positive and alpha/beta must be >= 1")
    values = np.asarray([lambda0 * alpha ** ORDER_LEVEL[order] * beta_memory ** memory for order, memory in BASIS_IDS], dtype=np.float64)
    if not np.all(np.isfinite(values)) or np.any(values <= 0):
        raise ValueError("basis-dependent lambda vector is not finite/positive")
    return values


def _lambda_vector_gate() -> dict[str, Any]:
    actual = _lambda_vector(1e-7, 2.0, 2.0)
    expected = np.asarray([1e-7, 2e-7, 4e-7, 2e-7, 4e-7, 4e-7, 8e-7, 8e-7, 1.6e-6, 3.2e-6], dtype=np.float64)
    return {"pass": bool(np.allclose(actual, expected, rtol=1e-12, atol=0.0)), "actual": actual, "expected": expected}


def _fit_weighted_normalized(phi_train: np.ndarray, y_train: np.ndarray, lambda0: float, alpha: float, beta_memory: float) -> dict[str, Any]:
    phi_train = np.asarray(phi_train, dtype=np.complex128)
    y_train = np.asarray(y_train, dtype=np.complex128).reshape(-1)
    scale = np.sqrt(np.mean(np.abs(phi_train) ** 2, axis=0))
    if not np.all(np.isfinite(scale)) or np.any(scale <= 0):
        raise RuntimeError("Invalid RMS scale.")
    phi_norm = phi_train / scale[None, :]
    n_samples = phi_norm.shape[0]
    lambda_vector = _lambda_vector(lambda0, alpha, beta_memory)
    penalty = np.diag(np.sqrt(n_samples * lambda_vector)).astype(np.complex128)
    phi_aug = np.vstack((phi_norm, penalty))
    y_aug = np.concatenate((y_train, np.zeros(K, dtype=np.complex128)))
    beta_hat, _, rank, singular_aug = np.linalg.lstsq(phi_aug, y_aug, rcond=None)
    singular_norm = np.asarray(np.linalg.svd(phi_norm, compute_uv=False), dtype=np.float64)
    return {
        "beta": np.asarray(beta_hat, dtype=np.complex128),
        "scale": scale,
        "rank": int(rank),
        "singular": singular_norm,
        "singular_augmented": np.asarray(singular_aug, dtype=np.float64),
        "lambda_vector": lambda_vector,
        "ridge_penalty": float(np.sum(lambda_vector * np.abs(beta_hat) ** 2)),
    }


