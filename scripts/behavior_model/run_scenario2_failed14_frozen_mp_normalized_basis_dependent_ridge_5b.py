def _scan_configurations(config_frame: pd.DataFrame, payload: dict[int, dict[str, tuple[np.ndarray, np.ndarray]]], workers: int) -> pd.DataFrame:
    tasks = [(int(row.config_id), float(row.lambda0), float(row.alpha), float(row.beta_memory), state_id, side) for row in config_frame.itertuples(index=False) for state_id in FAILED_STATE_IDS for side in ("Aend", "C2")]
    rows: list[dict[str, Any]] = []
    errors: list[str] = []
    print(f"weighted Ridge {config_frame.stage.iloc[0]} tasks: {len(tasks)}; workers={workers}", flush=True)
    with ProcessPoolExecutor(max_workers=workers, initializer=_worker_init, initargs=(payload,)) as executor:
        futures = [executor.submit(_cv_task, task) for task in tasks]
        for done, future in enumerate(as_completed(futures), start=1):
            try:
                rows.append(future.result())
            except Exception as exc:  # pragma: no cover
                errors.append(f"{type(exc).__name__}: {exc}")
            if done % 500 == 0 or done == len(futures):
                print(f"weighted Ridge {config_frame.stage.iloc[0]} tasks: {done}/{len(futures)}", flush=True)
    if errors:
        raise RuntimeError("weighted Ridge worker failure: " + " | ".join(errors[:5]))
    detail = pd.DataFrame(rows)
    summaries: list[dict[str, Any]] = []
    for config in config_frame.itertuples(index=False):
        current = detail.loc[detail["config_id"] == int(config.config_id)]
        a = current.loc[current.side == "Aend", "CV_NMSE_dB"].to_numpy(dtype=float)
        c = current.loc[current.side == "C2", "CV_NMSE_dB"].to_numpy(dtype=float)
        if a.size != 14 or c.size != 14:
            raise RuntimeError(f"config {config.config_id} has incomplete state-side CV results")
        a_median, c_median = float(np.median(a)), float(np.median(c))
        a_q75, c_q75 = float(np.quantile(a, 0.75)), float(np.quantile(c, 0.75))
        a_worst, c_worst = float(np.max(a)), float(np.max(c))
        summaries.append({"config_id": int(config.config_id), "stage": str(config.stage), "lambda0": float(config.lambda0), "alpha": float(config.alpha), "beta_memory": float(config.beta_memory), "log10_lambda0": float(config.log10_lambda0), "log2_alpha": float(config.log2_alpha), "log2_beta": float(config.log2_beta), "A_CV_median_dB": a_median, "A_CV_q75_dB": a_q75, "A_CV_worst_dB": a_worst, "C_CV_median_dB": c_median, "C_CV_q75_dB": c_q75, "C_CV_worst_dB": c_worst, "BalancedMedian_dB": max(a_median, c_median), "BalancedQ75_dB": max(a_q75, c_q75), "BalancedWorst_dB": max(a_worst, c_worst), "rank_min": int(current.rank_min.min())})
    return pd.DataFrame(summaries).sort_values("config_id").reset_index(drop=True)


def _select_configuration(frame: pd.DataFrame) -> tuple[pd.Series, dict[str, Any]]:
    best = float(frame["BalancedMedian_dB"].min())
    ties = frame.loc[np.abs(frame["BalancedMedian_dB"] - best) < TIE_TOLERANCE_DB].copy()
    ties = ties.sort_values(["BalancedQ75_dB", "BalancedWorst_dB", "alpha", "beta_memory", "lambda0"], ascending=[True, True, True, True, True], kind="mergesort")
    selected = ties.iloc[0]
    return selected, {"best_balanced_median_dB": best, "tie_count_within_1e-9_dB": int(ties.shape[0]), "selected_config_id": int(selected.config_id), "selected_lambda0": float(selected.lambda0), "selected_alpha": float(selected.alpha), "selected_beta_memory": float(selected.beta_memory)}


def _local_refinement_configs(coarse_best: pd.Series) -> list[tuple[float, float, float]]:
    log_lambda = float(coarse_best.log10_lambda0)
    log_alpha = float(coarse_best.log2_alpha)
    log_beta = float(coarse_best.log2_beta)
    configs: dict[tuple[float, float, float], tuple[float, float, float]] = {}
    for ll in np.arange(log_lambda - 0.5, log_lambda + 0.5 + 1e-12, 0.125):
        for la in np.arange(log_alpha - 0.75, log_alpha + 0.75 + 1e-12, 0.25):
            for lb in np.arange(log_beta - 0.75, log_beta + 0.75 + 1e-12, 0.25):
                ll_clipped = float(np.clip(ll, -12.0, -2.0))
                la_clipped = float(np.clip(la, 0.0, 5.0))
                lb_clipped = float(np.clip(lb, 0.0, 3.0))
                key = (round(ll_clipped, 12), round(la_clipped, 12), round(lb_clipped, 12))
                configs[key] = (10.0 ** ll_clipped, 2.0 ** la_clipped, 2.0 ** lb_clipped)
    return [configs[key] for key in sorted(configs)]


def _uniform_equivalence_gate(final_rows: pd.DataFrame) -> dict[str, Any]:
    if not UNIFORM_RESULT_FILE.is_file():
        raise FileNotFoundError(f"previous normalized uniform result missing: {UNIFORM_RESULT_FILE}")
    previous = pd.read_csv(UNIFORM_RESULT_FILE).set_index("state_id").loc[list(FAILED_STATE_IDS)]
    current = final_rows.set_index("state_id").loc[list(FAILED_STATE_IDS)]
    checks: list[dict[str, Any]] = []
    for state_id in FAILED_STATE_IDS:
        differences = {}
        for metric in ("A_train", "A_B", "C_train", "C_B"):
            current_value = float(current.loc[state_id, f"UniformNorm_{metric}"])
            old_value = float(previous.loc[state_id, f"Selected_{'A_train' if metric == 'A_train' else 'A_B' if metric == 'A_B' else 'C_train' if metric == 'C_train' else 'C_B'}"])
            differences[metric] = current_value - old_value
        checks.append({"state_id": int(state_id), "max_abs_difference_dB": float(max(abs(value) for value in differences.values())), "differences_dB": differences})
    maximum = max(item["max_abs_difference_dB"] for item in checks)
    return {"pass": bool(maximum < 1e-6), "maximum_abs_difference_dB": maximum, "checks": checks}


def _fit_final_rows(selected_lambda0: float, selected_alpha: float, selected_beta: float) -> tuple[pd.DataFrame, list[dict[str, float]]]:
    rows: list[dict[str, Any]] = []
    conditions: list[dict[str, float]] = []
    for state_id in FAILED_STATE_IDS:
        prepared = frozen_model.prepare_state(state_id)
        a_phi, a_y = _uniform_build_basis(prepared.aend_A_input, prepared.aend_A_output)
        c_phi, c_y = _uniform_build_basis(prepared.c2_C_input, prepared.c2_C_output)
        a_b_phi, a_b_y = _uniform_build_basis(prepared.aend_B_input, prepared.aend_B_output)
        c_b_phi, c_b_y = _uniform_build_basis(prepared.c2_B_input, prepared.c2_B_output)
        row: dict[str, Any] = {"state_id": int(state_id)}
        condition_row: dict[str, float] = {"state_id": float(state_id)}
        for label, train_phi, train_y, b_phi, b_y in (("A", a_phi, a_y, a_b_phi, a_b_y), ("C", c_phi, c_y, c_b_phi, c_b_y)):
            frozen_fit = _uniform_fit_raw_ridge(train_phi, train_y, FROZEN_LAMBDA)
            uniform_fit = _uniform_fit_normalized_ridge(train_phi, train_y, UNIFORM_LAMBDA)
            weighted_fit = _fit_weighted_normalized(train_phi, train_y, selected_lambda0, selected_alpha, selected_beta)
            raw_prediction = train_phi @ frozen_fit["theta"]
            raw_b_prediction = b_phi @ frozen_fit["theta"]
            uniform_prediction = (train_phi / uniform_fit["scale"][None, :]) @ uniform_fit["beta"]
            uniform_b_prediction = (b_phi / uniform_fit["scale"][None, :]) @ uniform_fit["beta"]
            weighted_prediction = (train_phi / weighted_fit["scale"][None, :]) @ weighted_fit["beta"]
            weighted_b_prediction = (b_phi / weighted_fit["scale"][None, :]) @ weighted_fit["beta"]
            for prefix, train_prediction, b_prediction in (("Frozen", raw_prediction, raw_b_prediction), ("UniformNorm", uniform_prediction, uniform_b_prediction), ("Weighted", weighted_prediction, weighted_b_prediction)):
                row[f"{prefix}_{label}_train"] = float(calculate_nmse(train_y, train_prediction))
                row[f"{prefix}_{label}_B"] = float(calculate_nmse(b_y, b_prediction))
                row[f"{prefix}_{label}_gap"] = row[f"{prefix}_{label}_B"] - row[f"{prefix}_{label}_train"]
            condition_row[f"{label}_raw_condition"] = float(np.linalg.cond(train_phi))
            condition_row[f"{label}_normalized_condition"] = float(np.linalg.cond(train_phi / uniform_fit["scale"][None, :]))
        for prefix in ("Frozen", "UniformNorm", "Weighted"):
            row[f"{prefix}_worst4"] = max(row[f"{prefix}_A_train"], row[f"{prefix}_A_B"], row[f"{prefix}_C_train"], row[f"{prefix}_C_B"])
        for suffix in ("A_train", "A_B", "C_train", "C_B", "worst4"):
            row[f"Weighted_minus_Frozen_{suffix}"] = row[f"Weighted_{suffix}"] - row[f"Frozen_{suffix}"]
        rows.append(row)
        conditions.append(condition_row)
        del prepared
    return pd.DataFrame(rows).sort_values("state_id").reset_index(drop=True), conditions


